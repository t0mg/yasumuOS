/// Complete multi-language translations for the yasumuOS Obsidian Handheld UI & RetroArch OSD.
#[derive(Debug, Copy, Clone, PartialEq, Eq)]
pub enum Language {
    En,
    Fr,
    Es,
    De,
    Ja,
    Zh,
}

impl Language {
    pub fn from_code(code: &str) -> Self {
        match code.trim().to_ascii_lowercase().as_str() {
            "fr" | "fr-fr" | "french" => Language::Fr,
            "es" | "es-es" | "spanish" => Language::Es,
            "de" | "de-de" | "german" => Language::De,
            "ja" | "ja-jp" | "jp" | "japanese" => Language::Ja,
            "zh" | "zh-cn" | "zh-hans" | "chinese" => Language::Zh,
            _ => Language::En,
        }
    }

    pub fn code(self) -> &'static str {
        match self {
            Language::En => "en",
            Language::Fr => "fr",
            Language::Es => "es",
            Language::De => "de",
            Language::Ja => "ja",
            Language::Zh => "zh",
        }
    }

    /// RetroArch `user_language` integer ID (`retroarch.cfg`).
    pub fn retroarch_user_language_id(self) -> u32 {
        match self {
            Language::En => 0,  // RETRO_LANGUAGE_ENGLISH
            Language::Ja => 1,  // RETRO_LANGUAGE_JAPANESE
            Language::Fr => 2,  // RETRO_LANGUAGE_FRENCH
            Language::Es => 3,  // RETRO_LANGUAGE_SPANISH
            Language::De => 4,  // RETRO_LANGUAGE_GERMAN
            Language::Zh => 12, // RETRO_LANGUAGE_CHINESE_SIMPLIFIED
        }
    }
}

